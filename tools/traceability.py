"""Spec traceability (XC-82): every check in the catalogue is normative or hardening, once.

    python3 tools/traceability.py            write docs/traceability.json and docs/TRACEABILITY.md
    python3 tools/traceability.py --check    exit 1 unless the committed table is complete, sound and fresh

A check is normative when its catalogue profile is normative: it tests a MUST or SHOULD clause of the x402 V2
specification or an extension, and its row carries the clause anchor that docs/check-ids.json already holds (XC-55).
Every other check is hardening: it tests safety beyond what the spec requires, and its row gives the reason, its
profile and one-line property. This tool adds no anchors of its own.

--check fails when a catalogue check has no row, when a check has more than one row or is in both classes, when a
normative row has no anchor or its anchor does not resolve to the pinned spec lines, when a hardening row has no
reason, and when the committed files differ from what the catalogue gives now. The table states counts per class,
never a percentage.
"""

from __future__ import annotations

import argparse
import importlib
import json
import os
import sys
from typing import Any

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from build_coverage import cell, key  # noqa: E402
from spec_anchors import anchored_text, digest  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
JSON_OUT = "docs/traceability.json"
MD_OUT = "docs/TRACEABILITY.md"
REGISTRY = "docs/check-ids.json"
CLASSES = ("normative", "hardening")
SCHEMA = "x402conf.traceability/1"


def load_catalog(root: str) -> dict[str, dict[str, Any]]:
    sys.path.insert(0, os.path.join(root, "src"))
    cat: dict[str, dict[str, Any]] = importlib.import_module("x402conf.spec").CATALOG
    return cat


def load_registry(root: str) -> tuple[dict[str, dict[str, Any]], dict[str, Any]]:
    """The registry's ids (property, profile) and its anchors, by check id."""
    with open(os.path.join(root, REGISTRY), encoding="utf-8") as f:
        reg = json.load(f)
    ids = {c["id"]: c for c in reg.get("ids", [])}
    anchors = {c["id"]: c.get("anchor") for c in reg.get("checks", [])}
    return ids, anchors


def build(catalog: dict[str, dict[str, Any]], ids: dict[str, dict[str, Any]], anchors: dict[str, Any]) -> dict[str, Any]:
    rows = []
    for cid in sorted(catalog, key=key):
        profile = catalog[cid]["profile"]
        prop = str(ids.get(cid, {}).get("property") or "")
        if profile == "normative":
            rows.append({"id": cid, "class": "normative", "profile": profile, "anchor": anchors.get(cid),
                         "reason": None, "property": prop})
        else:
            rows.append({"id": cid, "class": "hardening", "profile": profile, "anchor": None,
                         "reason": f"{profile}: {prop}" if prop else "", "property": prop})
    counts = {c: sum(r["class"] == c for r in rows) for c in CLASSES}
    return {"schema": SCHEMA, "source": ["src/x402conf/spec.py CATALOG", REGISTRY], "counts": counts, "rows": rows}


def render_md(table: dict[str, Any]) -> str:
    out = [
        "# Spec traceability",
        "",
        "Generated by `tools/traceability.py` from the check catalogue (`src/x402conf/spec.py`) and the spec anchors in "
        "`docs/check-ids.json`. Do not edit it by hand: run `python3 tools/traceability.py`; CI runs it with `--check`.",
        "",
        "Every check is in one of two classes. A **normative** check tests a MUST or SHOULD clause of the x402 V2 "
        "specification or one of its extensions, and its row names the pinned spec lines the clause is quoted from. A "
        "**hardening** check tests safety beyond what the spec requires, and its row gives the reason. This answers how "
        "much of the spec the suite tests with a count per class, not a percentage. What each check does and what it "
        "catches is in [COVERAGE.md](COVERAGE.md).",
        "",
        "| class | checks |",
        "|---|---|",
    ]
    out += [f"| {c} | {table['counts'][c]} |" for c in CLASSES]
    out += ["", "## Checks", "", "| id | class | spec anchor, or the reason for hardening |", "|---|---|---|"]
    for r in table["rows"]:
        if r["class"] == "normative" and isinstance(r["anchor"], dict):
            a = r["anchor"]
            lines = (f"line {a['line_start']}" if a["line_start"] == a["line_end"]
                     else f"lines {a['line_start']}-{a['line_end']}")
            what = f"`{a['spec_file']}` {lines} at `{str(a['upstream_commit'])[:12]}`: {cell(r['property'])}"
        else:
            what = cell(str(r["reason"] or ""))
        out.append(f"| {r['id']} | {r['class']} | {what} |")
    return "\n".join(out) + "\n"


def problems(table: Any, catalog: dict[str, dict[str, Any]], root: str) -> list[str]:
    """What keeps a table from being a complete, sound classification of the catalogue."""
    if not isinstance(table, dict) or table.get("schema") != SCHEMA or not isinstance(table.get("rows"), list):
        return [f"not a {SCHEMA} table"]
    out: list[str] = []
    classes: dict[str, list[str]] = {}
    for r in table["rows"]:
        cid, cls = r.get("id"), r.get("class")
        if cls not in CLASSES:
            out.append(f"{cid}: class {cls!r} is not normative or hardening")
            continue
        classes.setdefault(str(cid), []).append(cls)
        if cid not in catalog:
            out.append(f"{cid}: not a check in the catalogue")
        if cls == "normative":
            a = r.get("anchor")
            if not isinstance(a, dict):
                out.append(f"{cid}: a normative row with no spec anchor")
            else:
                try:
                    if digest(anchored_text(root, a)) != a.get("quoted_text_sha256"):
                        out.append(f"{cid}: its anchor's quoted text no longer matches {a.get('spec_file')}")
                except (OSError, ValueError, KeyError) as e:
                    out.append(f"{cid}: its anchor does not resolve: {e}")
        elif not str(r.get("reason") or "").strip():
            out.append(f"{cid}: a hardening row with no reason")
    for cid in catalog:
        got = classes.get(cid, [])
        if not got:
            out.append(f"{cid}: not classified")
        elif len(set(got)) > 1:
            out.append(f"{cid}: in both classes")
        elif len(got) > 1:
            out.append(f"{cid}: classified {len(got)} times")
    counts = {c: sum(r.get("class") == c for r in table["rows"]) for c in CLASSES}
    if table.get("counts") != counts:
        out.append(f"counts {table.get('counts')!r} do not match the rows {counts!r}")
    return out


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description="Classify every check as normative or hardening.")
    p.add_argument("--check", action="store_true", help="fail on an incomplete, unsound or stale committed table")
    p.add_argument("--root", default=ROOT)
    a = p.parse_args(argv)
    catalog = load_catalog(a.root)
    want = build(catalog, *load_registry(a.root))
    text = json.dumps(want, indent=1, ensure_ascii=False) + "\n"
    md = render_md(want)
    jpath, mpath = os.path.join(a.root, JSON_OUT), os.path.join(a.root, MD_OUT)
    if not a.check:
        with open(jpath, "w", encoding="utf-8") as f:
            f.write(text)
        with open(mpath, "w", encoding="utf-8") as f:
            f.write(md)
        print(f"wrote {JSON_OUT} and {MD_OUT}: " + ", ".join(f"{want['counts'][c]} {c}" for c in CLASSES))
        return 0
    try:
        with open(jpath, encoding="utf-8") as f:
            committed_text = f.read()
        with open(mpath, encoding="utf-8") as f:
            committed_md = f.read()
        committed = json.loads(committed_text)
    except (OSError, ValueError) as e:
        print(f"traceability: {e}", file=sys.stderr)
        return 1
    found = problems(committed, catalog, a.root) + problems(want, catalog, a.root)
    if committed_text != text or committed_md != md:
        found.append(f"{JSON_OUT} or {MD_OUT} is stale: run python3 tools/traceability.py")
    for x in dict.fromkeys(found):
        print(x, file=sys.stderr)
    if found:
        print(f"{len(set(found))} problem(s)")
        return 1
    print("ok " + ", ".join(f"{want['counts'][c]} {c}" for c in CLASSES))
    return 0


if __name__ == "__main__":
    sys.exit(main())
