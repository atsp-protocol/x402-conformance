#!/usr/bin/env python3
"""The compatibility matrix, generated from the implementation-matrix runs.

    python3 tools/compat_matrix.py --write [--root DIR]   rebuild docs/compat-matrix.json and the generated table in
                                                          docs/MATRIX.md from evidence/impl-matrix/*/run.json
    python3 tools/compat_matrix.py --check [--root DIR]   exit 1 when either is stale, a row has no run or no
                                                          SHA256SUMS, or a hash does not match its file

Each row is one directory evidence/impl-matrix/<stack>-<version>/ with the run.json the probe wrote, a README.md and
SHA256SUMS over both. The matrix carries, per row, the stack and version, the network graded, the tool, every check's
status, the run's path and the hashes from SHA256SUMS, so a reader can check a row against its evidence. Nothing in
the output depends on when it was generated. The table in docs/MATRIX.md sits between the compat-matrix markers;
the text around them is left alone.

Row format (XC-93): every row has an Environment (testnet, devnet, live-not-run or out-of-reach; these rows run on
loopback from source with testnet ids, so devnet), checks passed out of checks run, the failed count only (no check
names), the version tested, the run date linking the committed run.json, a "rerun / get listed" link and a "missing
check?" link. No score, rank or certification wording.

Opt-in (XC-96): a row whose README records the project's consent ("Listed with the project's consent: <issue or PR>",
written by tools/row_from_evidence.py) is the evidence of a listed project, shown through matrix/rows/<slug>.json by
tools/matrix_rows.py, which also writes its badge. A row without consent is the suite's own reference baseline (the
protocol's reference example servers): it is not a listing and has no badge.
"""
from __future__ import annotations

import hashlib
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ROWS = "evidence/impl-matrix"
JSON_OUT = "docs/compat-matrix.json"
MD_OUT = "docs/MATRIX.md"
START, END = "<!-- compat-matrix:start -->", "<!-- compat-matrix:end -->"
SCHEMA = "x402-conformance.compat-matrix/1"
HEADING = "## Reference baseline"
PAGES = "https://atsp-protocol.github.io/x402-conformance"
REPO = "https://github.com/atsp-protocol/x402-conformance"
ENVIRONMENTS = ("testnet", "devnet", "live-not-run", "out-of-reach")
RERUN = "#rerun-or-get-listed"
MISSING_CHECK = f"{REPO}/issues/new?template=check-proposal.yml"
NOT_RUN = ("not_applicable", "unsupported", "not_run", "skipped")
CONSENT_LINE = re.compile(r"Listed with the project's consent: (https://github\.com/\S+)")
INTRO = ("The suite's own reference baseline, not listings: stock example servers at pinned SDK versions, "
         "probed on loopback behind the facilitator double (R0 to R10), "
         "so the environment is devnet: local, from source, with testnet ids. "
         "Generated by `python3 tools/compat_matrix.py --write` from `evidence/impl-matrix/*/run.json`; CI fails when "
         "this table or `docs/compat-matrix.json` is stale, a row has no hashes, or a hash does not match its file. "
         "Each row links the run it was built from and the `SHA256SUMS` that pins it. Passed/run counts the checks that "
         "ran; failed is a count only. A row marked listed is a project's own evidence, with its consent in its README.")


def sha256(path: str) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 16), b""):
            h.update(chunk)
    return h.hexdigest()


def read_sums(path: str) -> dict[str, str]:
    out: dict[str, str] = {}
    with open(path, encoding="utf-8") as f:
        for line in f:
            m = re.match(r"^([0-9a-f]{64})\s+\*?(\S+)\s*$", line.strip())
            if m:
                out[m.group(2)] = m.group(1)
    return out


def rows(root: str) -> tuple[list[dict[str, object]], list[str]]:
    """Every row under evidence/impl-matrix, and the problems found while reading them."""
    base = os.path.join(root, ROWS)
    out: list[dict[str, object]] = []
    problems: list[str] = []
    for name in sorted(os.listdir(base)) if os.path.isdir(base) else []:
        d = os.path.join(base, name)
        if not os.path.isdir(d):
            continue
        run_path = os.path.join(d, "run.json")
        if not os.path.isfile(run_path):
            problems.append(f"{name}: no run.json")
            continue
        with open(run_path, encoding="utf-8") as f:
            run = json.load(f)
        sums_path = os.path.join(d, "SHA256SUMS")
        sums = read_sums(sums_path) if os.path.isfile(sums_path) else {}
        if not sums:
            problems.append(f"{name}: no SHA256SUMS")
        for file, want in sorted(sums.items()):
            p = os.path.join(d, file)
            if not os.path.isfile(p):
                problems.append(f"{name}: SHA256SUMS names {file}, which is missing")
            elif sha256(p) != want:
                problems.append(f"{name}: {file} does not match its hash in SHA256SUMS")
        if "run.json" not in sums and sums:
            problems.append(f"{name}: SHA256SUMS does not cover run.json")
        readme = os.path.join(d, "README.md")
        m = CONSENT_LINE.search(open(readme, encoding="utf-8").read()) if os.path.isfile(readme) else None
        results = run.get("results", [])
        target = ""
        if run.get("mode") in ("resource-GET-only", "resource-unpaid"):  # the queue's tier-1 run (XC-98, XC-110)
            target = next((str(r.get("target")) for r in results if isinstance(r, dict) and r.get("target")), "")
            results = [{"check": c.get("check"), "pass": c.get("pass") is True or c.get("severity") != "error",
                        "status": "pass" if c.get("pass") is True or c.get("severity") != "error" else "fail"}
                       for r in results if isinstance(r, dict) for c in r.get("checks", []) if isinstance(c, dict)]
        stack, _, version = name.rpartition("-")
        first = results[0].get("detail") if results and isinstance(results[0], dict) else None
        network = first.get("graded_on") if isinstance(first, dict) else None
        ran = [r for r in results if isinstance(r, dict) and r.get("status") not in NOT_RUN]
        passed = [r for r in ran if r.get("status") == "pass" or (r.get("pass") is True and r.get("status") is None)]
        out.append({
            "row": name, "environment": environment({"resource": target} if target else run), "stack": stack,
            "version": version, "network": network,
            "checks_run": len(ran), "checks_passed": len(passed), "failed_count": len(ran) - len(passed),
            "tool": run.get("tool"), "run_at": run.get("run_at"),
            "run": f"{ROWS}/{name}/run.json", "sums": f"{ROWS}/{name}/SHA256SUMS", "sha256": sums,
            "summary": run.get("summary"), "consent": m.group(1) if m else None,
            "checks": {str(r.get("check", "")).split(" ")[0]: r.get("status") for r in results if isinstance(r, dict)},
        })
    return out, problems


def environment(run: dict[str, object]) -> str:
    """devnet for a run on loopback (local, from source or fixtures), testnet for a public testnet endpoint."""
    target = str(run.get("resource") or run.get("target") or "")
    host = re.sub(r"^[a-z]+://", "", target).split("/")[0].split(":")[0]
    return "devnet" if host in ("127.0.0.1", "localhost", "::1", "") else "testnet"


def build_json(rs: list[dict[str, object]]) -> str:
    return json.dumps({"schema": SCHEMA, "rows": rs}, indent=1, ensure_ascii=False) + "\n"


def build_table(rs: list[dict[str, object]]) -> str:
    lines = [START, "", INTRO, "",
             "| row | environment | stack | version tested | network | passed/run | failed | last run | hashes | listing "
             "| rerun / get listed | missing check? |",
             "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in rs:
        sha = r["sha256"] if isinstance(r["sha256"], dict) else {}
        short = sha.get("run.json", "")[:12] or "missing"
        date = str(r.get("run_at") or "")[:10] or "run.json"
        badge = f"[listed]({PAGES}/matrix/#{r['row']})" if r.get("consent") else "baseline"
        lines.append(f"| <a id=\"row-{r['row']}\"></a>{r['row']} | {r['environment']} | {r['stack']} | {r['version']} | "
                     f"`{r['network']}` | {r['checks_passed']}/{r['checks_run']} | {r['failed_count']} | "
                     f"[{date}](../{r['run']}) | [`{short}`](../{r['sums']}) | {badge} | "
                     f"[rerun]({RERUN}) | [propose a check]({MISSING_CHECK}) |")
    lines += ["", END]
    return "\n".join(lines)


def with_table(md: str, table: str) -> str:
    """docs/MATRIX.md with the generated table replaced, or appended as its own section when absent."""
    i, j = md.find(START), md.find(END)
    if i >= 0 and j > i:
        return md[:i] + table + md[j + len(END):]
    return md.rstrip("\n") + f"\n\n{HEADING}\n\n{table}\n"


def main(argv: list[str]) -> int:
    root = ROOT
    if "--root" in argv:
        root = os.path.abspath(argv[argv.index("--root") + 1])
    rs, problems = rows(root)
    want_json = build_json(rs)
    md_path = os.path.join(root, MD_OUT)
    md = open(md_path, encoding="utf-8").read() if os.path.isfile(md_path) else ""
    want_md = with_table(md, build_table(rs))
    if "--write" in argv:
        with open(os.path.join(root, JSON_OUT), "w", encoding="utf-8") as f:
            f.write(want_json)
        with open(md_path, "w", encoding="utf-8") as f:
            f.write(want_md)
        print(f"wrote {JSON_OUT} and the table in {MD_OUT}: {len(rs)} row(s)")
        for p in problems:
            print(f"compat-matrix: {p}")
        return 1 if problems else 0
    if "--check" in argv:
        json_path = os.path.join(root, JSON_OUT)
        have_json = open(json_path, encoding="utf-8").read() if os.path.isfile(json_path) else ""
        if have_json != want_json:
            problems.append(f"{JSON_OUT} is stale: run python3 tools/compat_matrix.py --write and commit it")
        if START not in md or END not in md:
            problems.append(f"{MD_OUT} has no compat-matrix table: run python3 tools/compat_matrix.py --write")
        elif md != want_md:
            problems.append(f"the table in {MD_OUT} is stale or hand-edited: run python3 tools/compat_matrix.py --write")
        for r in rs:
            if r["environment"] not in ENVIRONMENTS:
                problems.append(f"{r['row']}: environment {r['environment']!r} is not one of {', '.join(ENVIRONMENTS)}")
        for p in problems:
            print(f"compat-matrix: {p}")
        print(f"compat matrix: {len(rs)} row(s), {len(problems)} problem(s)")
        return 1 if problems else 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
